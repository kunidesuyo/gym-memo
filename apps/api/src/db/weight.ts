/**
 * 重量は DB にグラム単位の整数で持ち、API には kg で公開する。
 * 変換をここに閉じ込めることで、保存形式が web 側に漏れない。
 */

/**
 * kg → g。
 *
 * ⚠️ `Math.round` は必須。`1.005 * 1000` は `1004.9999999999999` になる。
 * 小数2桁を15万通り総当たりしたところ 1,762 件がこの形で、round を挟めば
 * 小数3桁（g の限界）まで往復が一致することを確認済み。
 */
export const toG = (kg: number): number => Math.round(kg * 1000)

/**
 * g → kg。
 *
 * 整数を1000で割った結果は「その小数値の最近傍 double」になり、
 * 同じ小数文字列をパースした値と一致する。往復しても崩れない。
 */
export const toKg = (g: number): number => g / 1000
