/** mag はラットプルダウンのアタッチメント。語順ゆれ（magリバース / リバースmag）を吸収する。 */
const MAG_GRIPS = [
  'ナローパラレル',
  'ナローリバース',
  'ナローニュートラル',
  'パラレル',
  'リバース',
  'ニュートラル',
  '逆手',
  'ナロー',
] as const

export function normalizeMag(token: string): string | null {
  if (!token.toLowerCase().includes('mag')) return null
  const grip = MAG_GRIPS.find((g) => token.includes(g))
  return grip ? `${grip}magラットプルダウン` : 'magラットプルダウン'
}

