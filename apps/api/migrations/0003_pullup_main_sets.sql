-- 懸垂のメインセットを回数で補正する。スキーマ変更は無く、DML だけの手書き移行。
--
-- 懸垂は10回でアシストを減らしていき、本番は5回。本番が6本続く日があり、
-- 0002 の「ラスト3」では前半3本を取りこぼしていた。
--   -18×10 -18×10 -14×5 -14×5 -9×5 -9×5 -9×5 -9×5
--                 └──────── ここから全部が本番 ────────┘
-- 逆向き（10回は常にアップ）は成り立たない。130日のうち125日は10回しかやっておらず、
-- その日は10回が本番。**5回なら本番**という向きだけを足す。
UPDATE `sets` SET `is_main_set` = true
WHERE `reps` <= 5
  AND `exercise_id` IN (SELECT `id` FROM `exercises` WHERE `name` = '懸垂');
